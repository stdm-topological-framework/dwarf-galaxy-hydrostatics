def get_galaxy_geometry_blueprint(galaxy_type):
    """
    Автоматический экспертный селектор трехмерной геометрии и формул потенциала
    в зависимости от морфологического класса галактики.
    """
    galaxy_type = galaxy_type.lower().strip()
    
    blueprint = {
        "имя_класса": "Неизвестный объект",
        "геометрия_3d": "Нет данных",
        "формула_потенциала": "Нет данных",
        "параметры_сетки": [],
        "литература": "Общий курс астрофизики"
    }
    
    # 1. Класс Блинчик / Рупор (Дисковые, Спиральные, UDG вроде CamB)
    if "диск" in galaxy_type or "блин" in galaxy_type or "рупор" in galaxy_type or "camb" in galaxy_type:
        blueprint["имя_класса"] = "Дисковая / Ультрадиффузная система (Класс S/S0/UDG)"
        blueprint["геометрия_3d"] = "Сплюснутый трехмерный диск с возможным раздуванием (flaring) к периферии."
        blueprint["формула_потенциала"] = "Потенциал Миямото-Нагаи (Miyamoto-Nagai): \n  Phi(R,z) = -GM / sqrt(R^2 + (a + sqrt(z^2 + b^2))^2)"
        blueprint["параметры_сетки"] = ["M (Масса)", "R (Радиальный радиус)", "z (Вертикальная ось)", "a (Масштаб диска)", "b (Толщина)"]
        blueprint["литература"] = "Binney & Tremaine 'Galactic Dynamics', Глава 2.3 (Потенциалы дисков)"

    # 2. Класс Сфера (Идеальные шаровые скопления, карликовые сфероидальные)
    elif "сфер" in galaxy_type or "шар" in galaxy_type:
        blueprint["имя_класса"] = "Сферически-симметричная система (Класс E0 / dSph)"
        blueprint["геометрия_3d"] = "Идеальный 3D-шар. Плотность зависит только от абсолютного радиуса r."
        blueprint["формула_потенциала"] = "Потенциал Пламмера (Plummer model): \n  Phi(r) = -GM / sqrt(r^2 + b^2)"
        blueprint["параметры_сетки"] = ["M (Масса)", "r (Абсолютный радиус от центра)", "b (Масштаб ядра сглаживания)"]
        blueprint["литература"] = "Plummer (1911) / 'Galactic Dynamics', Глава 2.2 (Сферические потенциалы)"

    # 3. Класс Мяч для регби / Дыня / Эллипс (Эллиптические массивные системы)
    elif "эллипс" in galaxy_type or "дыня" in galaxy_type or "мяч" in galaxy_type:
        blueprint["имя_класса"] = "Вытянутый/Сплюснутый Эллипсоид (Класс E1-E7)"
        blueprint["геометрия_3d"] = "Трехосный или трехосно-симметричный эллипсоид (арбуз, дыня или регбийный мяч)."
        blueprint["формула_потенциала"] = "Профиль Хернквиста (Hernquist model) или потенциал идеального сфероида: \n  Phi(r) = -GM / (r + a)"
        blueprint["параметры_сетки"] = ["M (Масса)", "r_abc (Эллиптические координаты с учетом осей a, b, c)"]
        blueprint["литература"] = "Hernquist (1990) / Чандрасекар 'Эллипсоидальные фигуры равновесия'"

    # 4. Класс Хаос / Рваные клочья (Неправильные галактики)
    elif "хаос" in galaxy_type or "неправильн" in galaxy_type or "клоч" in galaxy_type:
        blueprint["имя_класса"] = "Нерегулярная хаотическая система (Класс Irr)"
        blueprint["геометрия_3d"] = "Полное отсутствие симметрии. Геометрия рваных клочьев газа после приливного разрушения."
        blueprint["формула_потенциала"] = "Аналитической формулы НЕТ. Требуется численное N-body интегрирование сетки Пуассона: \n  N-Body Сетка: [Набор точечных масс Ньютона в 3D пространстве]"
        blueprint["параметры_сетки"] = ["X, Y, Z (Массив координат каждой газовой/звездной точки)", "m_i (Масса каждой точки)"]
        blueprint["литература"] = "Хокни & Иствуд 'Численное моделирование методом частиц'"
        
    else:
        return "⚠️ Геометрический класс не распознан. Уточните форму (диск, сфера, эллипс или хаос)."

    # Красивый вывод архитектуры
    print(f"🧬 ГЕОМЕТРИЧЕСКИЙ КЛАСС: {blueprint['имя_класса']}")
    print(f"📐 3D Форма: {blueprint['геометрия_3d']}")
    print(f"🧮 Математический аппарат: {blueprint['формула_потенциала']}")
    print(f"📊 Переменные для кода Python: {blueprint['параметры_сетки']}")
    print(f"📚 Где читать формулы: {blueprint['литература']}")
    print("-" * 80)

# =====================================================================
